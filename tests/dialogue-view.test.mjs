import assert from 'node:assert/strict';
import {initialState,newTask} from '../frontend/src/core.js';
import {initCatalog} from '../frontend/src/catalog.js';
import {initOffice,seedOfficeTask} from '../frontend/src/office-model.js';
import {syncAgentThreads,focusAgentTask,selectedAgentTask} from '../frontend/src/agent-conversations.js';
import {renderAgentConversation,handleConversation,inputConversation} from '../frontend/src/conversation-ui.js';
import {renderOffice} from '../frontend/src/office-ui.js';
let checks=0;const ok=(value,label)=>{assert.ok(value,label);checks++;};
const state=initialState();initCatalog(state);initOffice(state);syncAgentThreads(state);
const task=seedOfficeTask(newTask('分析示例经营变化，给出复盘草稿'),'review',{agentId:'personal'});state.tasks.push(task);syncAgentThreads(state);focusAgentTask(state,task);
const c={state,ui:{route:'agent/personal'},currentTask(){return selectedAgentTask(state,'personal');},save(){syncAgentThreads(state);},render(){}};
const count=state.tasks.length;let html=renderAgentConversation(c);
ok(html.includes('<h2>对话摘要</h2>'),'normal conversation defaults to summary');
ok(!html.includes('aria-label="可编辑小队计划"'),'normal conversation does not force a workflow canvas');
ok(html.includes('d-agent-chips'),'delegation appears as inline task chips');
ok(html.includes('对话产物')&&html.includes('子智能体')&&html.includes('后台任务'),'summary keeps outputs, children and execution visible');
ok(!html.includes('小队模板')&&!html.includes('保存模板'),'normal conversation has no squad template actions');
ok(!html.includes('cv-panel-controls'),'simulation controls stay out of the normal composer');
ok(html.includes('本地电脑')&&html.includes('按需确认'),'composer exposes environment and concrete approval policy');
ok(state.tasks.length===count,'rendering a conversation does not create work');
task.office.view='replay';html=renderAgentConversation(c);
ok(html.includes('cv-summary-panel'),'saved task view does not override the default summary');
c.ui.cvPanelMode='work';html=renderAgentConversation(c);
ok(html.includes('cv-detail-panel')&&html.includes('data-office-view="replay"'),'explicit work mode opens the selected task view');
ok(html.includes('返回对话摘要'),'detailed work has an explicit way back');
task.office.phase='complete';html=renderAgentConversation(c);ok(!html.includes('小队模板')&&!html.includes('保存模板'),'completed work no longer offers squad template saving');task.office.phase='plan';
ok(handleConversation('cv:summary',{dataset:{}},c)&&c.ui.cvPanelMode==='summary','returning to prose restores summary');
ok(handleConversation('office:view',{dataset:{view:'plan'}},c)===false&&c.ui.cvPanelMode==='work','plan opens only through an explicit action');
c.ui.cvPanelMode='summary';handleConversation('viewer:open',{dataset:{}},c);
ok(c.ui.cvPanelMode==='work'&&task.office.view==='files','artifact opens in the same conversation');
handleConversation('viewer:close',{dataset:{}},c);
ok(c.ui.cvPanelMode==='summary','closing the artifact returns to summary');
inputConversation({dataset:{live:'cv:draft',agent:'personal'},value:'/数据'},c);
ok(c.ui.cvSkillAgent==='personal'&&c.ui.cvSkillQuery==='数据','slash opens a contextual skill picker');
inputConversation({dataset:{live:'cv:draft',agent:'personal'},value:'@数据'},c);
ok(c.ui.cvMentionAgent==='personal'&&!c.ui.cvSkillAgent,'mention picker replaces the slash picker');
c.ui.route='templates';html=renderOffice(c);
ok(!html.includes('小队模板')&&!html.includes('保存模板'),'retired deep link cannot expose the template product');
console.log(`${checks} dialogue-view assertions passed: prose-first summary, explicit work panels, contextual composer, no implicit task and retired template entry.`);
