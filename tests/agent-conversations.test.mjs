import assert from 'node:assert/strict';
import {initialState,newTask} from '../frontend/src/core.js';
import {initOffice,seedOfficeTask,startRun,event} from '../frontend/src/office-model.js';
import {agentThread,addAgentMessage,focusAgentTask,selectedAgentTask,syncAgentThreads,classifyAgentMessage} from '../frontend/src/agent-conversations.js';
import {sendConversation} from '../frontend/src/conversation-ui.js';
let checks=0;
const ok=(condition,label)=>{assert.ok(condition,label);checks++;};
const state=initialState();initOffice(state);const taskCount=state.tasks.length;
syncAgentThreads(state);
ok(state.tasks.length===taskCount,'opening Agent does not create a task');
ok(state.office.agents[0].id==='personal'&&state.office.agents[0].pinned,'personal Agent is always pinned');
ok(agentThread(state,'research').messages.length===1,'new Agent has one welcome');
ok(!selectedAgentTask(state,'research'),'new Agent has no implicit active task');
ok(!syncAgentThreads(state),'repeat synchronization is idempotent');
agentThread(state,'research').draft='研究背景';agentThread(state,'product').draft='产品背景';
ok(agentThread(state,'research').draft==='研究背景','Agent drafts stay independent');
const a=seedOfficeTask(newTask('经营复盘 A'),'review',{agentId:'bi'});
const b=seedOfficeTask(newTask('产品方案 B'),'proposal',{agentId:'product'});
state.tasks.push(a,b);syncAgentThreads(state);focusAgentTask(state,a);
ok(selectedAgentTask(state,'bi')===a,'focus selects the correct Agent task');
ok(!agentThread(state,'product').messages.some(m=>m.taskId===a.id),'another Agent never receives the task history');
const n=agentThread(state,'bi').messages.length;syncAgentThreads(state);
ok(agentThread(state,'bi').messages.length===n,'task messages migrate once');
startRun(a);syncAgentThreads(state);const runningMessages=agentThread(state,'bi').messages.length;syncAgentThreads(state);
ok(agentThread(state,'bi').messages.length===runningMessages,'milestones never duplicate');
ok(agentThread(state,'bi').messages.some(m=>m.kind==='run'),'execution has a conversational milestone');
event(a,'数据连接中断','示例连接失效','failure');syncAgentThreads(state);
ok(agentThread(state,'bi').messages.some(m=>m.kind==='failure'&&m.text.includes('保留')),'failure explains preservation and recovery');
const thread=agentThread(state,'bi');thread.activeTaskId=null;thread.newTopic=true;syncAgentThreads(state);
ok(!selectedAgentTask(state,'bi'),'new topic remains unbound after synchronization');
const c=seedOfficeTask(newTask('另一项经营复盘'),'review',{agentId:'bi'});state.tasks.push(c);syncAgentThreads(state);
ok(!selectedAgentTask(state,'bi'),'background task arrival does not override explicit new topic');
focusAgentTask(state,a);syncAgentThreads(state);
ok(selectedAgentTask(state,'bi')===a,'explicit historical selection survives synchronization');
const wrong=agentThread(state,'product');wrong.activeTaskId=a.id;syncAgentThreads(state);
ok(!selectedAgentTask(state,'product')&&wrong.activeTaskId===null,'cross Agent active IDs are rejected');
addAgentMessage(state,'research','user','一条背景',{key:'stable'});addAgentMessage(state,'research','user','重复背景',{key:'stable'});
ok(agentThread(state,'research').messages.filter(m=>m.key==='stable').length===1,'stable messages are deduplicated');
state.office.agents.find(a=>a.id==='research').pinned=false;syncAgentThreads(state);
ok(agentThread(state,'research').draft==='研究背景','unpinning retains conversation and draft');
ok(classifyAgentMessage('你能帮我做什么？',null)==='about','capability query stays conversation');
ok(classifyAgentMessage('你好',null)==='about','greeting stays conversation');
ok(classifyAgentMessage('帮我做一份经营复盘',null)==='goal','concrete goal creates work');
ok(classifyAgentMessage('补充渠道差异分析',a)==='refine','requirements target current work');
ok(classifyAgentMessage('数据来源是什么？',a)==='question','source question does not create another task');
ok(classifyAgentMessage('同意',a)==='approval','generic approval opens review only');
const ctx={state,ui:{},save(){syncAgentThreads(state);},render(){},startTask(){throw Error('unexpected new task');}};
const before=state.tasks.length;sendConversation(ctx,'research','你能帮我做什么？');
ok(state.tasks.length===before,'sending a question never calls task creation');
ok(agentThread(state,'research').draft==='','sending clears persistent draft');
focusAgentTask(state,a);const approval=a.office.approval;sendConversation(ctx,'bi','同意');
ok(a.office.approval===approval&&a.office.phase==='running','chat approval cannot bypass concrete confirmation');
ok(a.office.view==='approval','approval request opens the right panel');
sendConversation(ctx,'bi','暂停');
ok(a.office.phase==='paused','conversation can pause execution');
sendConversation(ctx,'bi','补充渠道变化的原因');
ok(a.office.requirements.includes('补充渠道变化的原因'),'requirements are retained by the selected task');
ok(!b.office.requirements,'requirements do not spill into another task');
sendConversation(ctx,'bi','继续执行');ok(a.office.phase==='running','conversation can resume execution');
const source={id:'local-ref',name:'本地资料',text:'示例内容'};agentThread(state,'research').context=[source];
const goalCtx={...ctx,startTask(prompt,options){const made=seedOfficeTask(newTask(prompt,options),'review',options);state.tasks.push(made);return made.id;}};
sendConversation(goalCtx,'research','帮我准备经营复盘');const researchWork=selectedAgentTask(state,'research');
ok(researchWork.context[0].name==='本地资料','Agent references bind to the new task');
ok(researchWork.context[0]!==source,'bound reference is a snapshot');
ok(agentThread(state,'research').context.length===0,'submitted reference draft is cleared');
ok(!b.context.some(r=>r.id==='local-ref'),'references do not leak into another Agent task');
state.tasks=state.tasks.filter(t=>t.id!==a.id);syncAgentThreads(state);
ok(!selectedAgentTask(state,'bi'),'removed task clears active work while retaining conversation');
console.log(`${checks} conversation assertions passed: persistent Agent threads, no implicit task, isolation, draft retention, deduplication, contextual controls and concrete approval boundaries.`);
